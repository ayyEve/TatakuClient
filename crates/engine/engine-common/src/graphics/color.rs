use crate::prelude::*;
use common::reflect::*;
#[derive(Reflect)]
#[derive(Clone, Copy, Debug, PartialEq)]
#[derive(serde::Serialize, serde::Deserialize)]
#[serde(from = "String", into = "String")]
pub struct Color {
    pub r: ColorField,
    pub g: ColorField,
    pub b: ColorField,
    pub a: ColorField,
}
// constant colors
#[allow(dead_code)]
impl Color {

    #[inline]
    pub const fn new(
        r: ColorField, 
        g: ColorField, 
        b: ColorField, 
        a: ColorField
    ) -> Self { 
        Self {
            r, 
            g, 
            b, 
            a,
        } 
    }

    #[inline]
    pub const fn new_f32(
        r: f32, 
        g: f32, 
        b: f32, 
        a: f32
    ) -> Self { 
        Self {
            r: ColorField::new_f32(r), 
            g: ColorField::new_f32(g), 
            b: ColorField::new_f32(b), 
            a: ColorField::new_f32(a),
        } 
    }

    pub const fn new_all(n: ColorField) -> Self {
        Self {
            r: n,
            g: n,
            b: n,
            a: n,
        }
    }

    pub const fn with_alpha(mut self, a: ColorField) -> Self {
        self.a = a;
        self
    }
    pub const fn with_alpha_f32(self, a: f32) -> Self {
        self.with_alpha(ColorField::new_f32(a))
    }

    pub fn from_hex(hex: impl AsRef<str>) -> Self {
        let hex = hex.as_ref();
        Self::try_from_hex(hex).unwrap_or_else(|| {
            println!("malformed hex: '{hex}'"); 
            Color::WHITE
        })
    }

    pub fn try_from_hex(hex: impl AsRef<str>) -> Option<Color> {
        let hex = hex.as_ref();
        let chars = hex.trim_matches('#').chars().collect::<Vec<char>>();
        fn parse(c1: char, c2: char) -> Option<u8> {
            u8::from_str_radix(
                &format!("{c1}{c2}"), 
                16
            ).ok()
        }

        match chars.len() {
            3 => { // rgb
                let r = parse(chars[0], chars[0])?;
                let g = parse(chars[1], chars[1])?;
                let b = parse(chars[2], chars[2])?;
                let a = 255;

                Some(Self::new_rgba8(r, g, b, a))
            }
            4 => { // rgba
                let r = parse(chars[0], chars[0])?;
                let g = parse(chars[1], chars[1])?;
                let b = parse(chars[2], chars[2])?;
                let a = parse(chars[3], chars[3])?;

                Some(Self::new_rgba8(r, g, b, a))
            }
            6 => { //rrggbb
                let r = parse(chars[0], chars[1])?;
                let g = parse(chars[2], chars[3])?;
                let b = parse(chars[4], chars[5])?;
                let a = 255;

                Some(Self::new_rgba8(r, g, b, a))
            }
            8 => { //rrggbbaa
                let r = parse(chars[0], chars[1])?;
                let g = parse(chars[2], chars[3])?;
                let b = parse(chars[4], chars[5])?;
                let a = parse(chars[6], chars[7])?;

                Some(Self::new_rgba8(r, g, b, a))
            }

            _ => None
        }
    }

    pub const fn new_rgb8(r: u8, g: u8, b: u8) -> Self {
        Self::new_rgba8(r, g, b, ColorField::MAX_VAL)
    }
    
    pub const fn new_rgba8(r: u8, g: u8, b: u8, a: u8) -> Self {
        Self { 
            r: ColorField::new_u8(r), 
            g: ColorField::new_u8(g), 
            b: ColorField::new_u8(b), 
            a: ColorField::new_u8(a)
        }
    }

    pub fn to_hex(self) -> String {
        let r = self.r.to_u8();
        let g = self.g.to_u8();
        let b = self.b.to_u8();
        let a = self.a.to_u8();

        format!("#{r:02X}{g:02X}{b:02X}{a:02X}")
    }
}
impl Default for Color {
    fn default() -> Self {
        Self::WHITE
    }
}

macro_rules! const_color {
    ($($name:ident = {r:$r:expr,g:$g:expr,b:$b:expr,a:$a:expr});*) => {
        #[allow(clippy::excessive_precision)]
        impl Color {
            $(
                pub const $name:Color = Color::new_f32($r, $g, $b, $a);
            )*

            pub fn from_name(s: &str) -> Option<Self> {
                match s {
                    $(
                        stringify!($name) 
                        | paste::paste!(stringify!([<$name:lower>])) => Some(Self::$name),
                    )*

                    _ => None,
                }
            }
        }
    }
}

